ALTER TABLE users
    ADD COLUMN IF NOT EXISTS display_name TEXT NOT NULL DEFAULT '',
    ADD COLUMN IF NOT EXISTS bio TEXT NOT NULL DEFAULT '',
    ADD COLUMN IF NOT EXISTS avatar_url TEXT;

UPDATE users
SET display_name = left(split_part(email, '@', 1), 60)
WHERE display_name = '';

CREATE TABLE IF NOT EXISTS articles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    summary TEXT NOT NULL DEFAULT '',
    body TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_articles_created_at
    ON articles (created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_articles_author_id_created_at
    ON articles (author_id, created_at DESC, id DESC);

CREATE TABLE IF NOT EXISTS author_follows (
    follower_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    author_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (follower_id, author_id),
    CHECK (follower_id <> author_id)
);

CREATE INDEX IF NOT EXISTS idx_author_follows_author
    ON author_follows (author_id, follower_id);

CREATE TABLE IF NOT EXISTS article_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    article_id BIGINT NOT NULL REFERENCES articles(id) ON DELETE CASCADE,
    author_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    body TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_article_comments_article_created
    ON article_comments (article_id, created_at, id);

CREATE TABLE IF NOT EXISTS article_reactions (
    article_id BIGINT NOT NULL REFERENCES articles(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    reaction TEXT NOT NULL CHECK (reaction IN ('like', 'dislike')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (article_id, user_id)
);

ALTER TABLE orders
    ADD COLUMN IF NOT EXISTS order_type TEXT NOT NULL DEFAULT 'service'
    CHECK (order_type IN ('service', 'publication_plan'));

CREATE UNIQUE INDEX IF NOT EXISTS idx_one_pending_publication_plan_per_user
    ON orders (user_id)
    WHERE order_type = 'publication_plan' AND status IN ('pending', 'processing');
CREATE INDEX IF NOT EXISTS idx_completed_publication_plan_per_user
    ON orders (user_id, status)
    WHERE order_type = 'publication_plan';
